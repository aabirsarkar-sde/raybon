                                    <p>Filter presses dewater sludge by forcing it through filter cloths under high pressure. Unlike a centrifuge, a filter press applies sustained pressure rather than shear, so the polymer must produce a floc that resists compression and keeps the cloth open rather than blinding it.</p>

                                    <p>Raybon Chemicals supplies polyelectrolytes and coagulants matched to plate-and-frame and membrane filter presses, drawn from the Solenis ZETAG and PRAESTOL ranges.</p>

                                    <h5>Polymer selection for filter presses</h5>
                                    <p>Most filter press applications handle inorganic sludge &mdash; lime, gypsum, metal hydroxide and mineral fines &mdash; and are best served by <a href="anionic-polyelectrolytes.php">anionic</a> or non-ionic polyelectrolytes of medium to high molecular weight. Where the feed is organic or mixed, a <a href="cationic-polyelectrolytes.php">cationic</a> grade is used, usually at lower molecular weight than a centrifuge would require.</p>

