                                        <li>Raw water and municipal drinking water clarification, using approved grades</li>
                                        <li>Steel, paper and petroleum process water recovery</li>
                                    </ul>

                                    <h5>Clarification and settling</h5>
                                    <p>As a settling agent, an anionic polyelectrolyte bridges fine suspended solids into flocs heavy enough to settle under gravity. In a clarifier or settling tank this raises the settling rate, drops the sludge blanket and leaves a visibly clearer overflow. Typical clarification duties include:</p>
                                    <ul>
                                        <li>Primary and secondary clarifier performance in ETPs and STPs</li>
                                        <li>Raw water and river water clarification ahead of filtration</li>
                                        <li>Process water recovery and recycle in steel, paper and mineral plants</li>
                                        <li>Tailings and washery effluent settling</li>
                                        <li>Reducing carryover of suspended solids to downstream filters</li>
                                    </ul>
                                    <p>Where the feed carries a high colloidal load, a coagulant dosed ahead of the flocculant usually outperforms increasing the polymer dose on its own. Charge is neutralised first, then the polymer bridges the destabilised particles.</p>

                                    <h5>Food-grade and drinking water applications</h5>
                                    <p>Our range includes anionic polyelectrolytes approved for potable water treatment, used in municipal drinking water clarification and raw water treatment where the polymer must meet food-contact and potable-water standards. Confirm the specific approval you require when requesting a datasheet, as approvals differ by grade and by jurisdiction.</p>

                                    <h5>Choosing an anionic grade</h5>
                                    <p>For anionic polymers, molecular weight generally matters more than charge density. Higher molecular weight produces larger flocs and faster settling, which suits quiescent settling in a clarifier or thickener. Lower molecular weight, higher charge grades give tighter flocs that survive pumping and agitation, which suits filter press feed lines.</p>

