                                    <p><strong>Anionic polyelectrolytes</strong> are negatively charged, water-soluble polymers used to flocculate inorganic sludges and slurries &mdash; lime, gypsum, mineral tailings, coal fines and process slurries &mdash; from industrial effluent and mineral processing. They work primarily by bridging rather than charge neutralisation, producing large, dense, fast-settling flocs with clear supernatant.</p>

                                    <p>Raybon Chemicals supplies anionic polyelectrolytes from the Solenis ZETAG and PRAESTOL ranges in powder and emulsion form, including food-grade and potable-water approved products for drinking water clarification.</p>

                                    <p>Depending on the duty they perform, anionic polyelectrolytes are also sold and specified as <strong>anionic flocculants</strong>, <strong>anionic poly</strong>, <strong>settling agents</strong>, <strong>clarifying agents</strong> or <strong>thickening agents</strong>. These describe the same family of products applied to different stages of the process, not different chemistries.</p>

                                    <h5>Where anionic polyelectrolytes are used</h5>
                                    <ul>
                                        <li>Lime and gypsum slurry dewatering</li>
                                        <li>Filter press and plate-and-frame dewatering of inorganic sludge</li>
                                        <li>Primary clarification and gravity thickening</li>
