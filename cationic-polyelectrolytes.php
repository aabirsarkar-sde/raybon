                                    <h5>Choosing charge density and molecular weight</h5>
                                    <p>Two variables govern cationic polymer performance. <strong>Charge density</strong> must match the charge demand of the sludge &mdash; a highly digested or heavily biological sludge carries more charge and needs a higher-charge polymer. <strong>Molecular weight</strong> governs floc size and shear resistance &mdash; a decanter centrifuge tears apart a weak floc, so high-shear machines need ultra-high molecular weight grades.</p>

                                    <p>Over-dosing a low-charge polymer to compensate for a charge mismatch is the most common and most expensive error we see in Indian plants. It raises consumption, blinds belts and can re-stabilise the floc entirely.</p>

