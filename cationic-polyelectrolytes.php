                                    <p><strong>Cationic polyelectrolytes</strong> are positively charged, water-soluble polymers used to dewater organic and biological sludge from sewage treatment plants and industrial effluent treatment plants. The positive charge neutralises the negative surface charge carried by biological solids, allowing fine particles to bridge into large, strong flocs that release water under pressure or centrifugal force.</p>

                                    <p>Raybon Chemicals supplies cationic polyelectrolytes from the Solenis ZETAG and PRAESTOL ranges, in powder and emulsion form, across the full span of charge density and molecular weight.</p>

                                    <h5>Where cationic polyelectrolytes are used</h5>
                                    <ul>
                                        <li>Sewage and municipal sludge dewatering</li>
                                        <li>Biological and surplus activated sludge from ETPs and STPs</li>
                                        <li>Decanter centrifuge, belt press and volute screw press dewatering</li>
                                        <li>Dissolved air flotation (DAF) for oily and fibrous effluent</li>
                                        <li>Gravity belt and drum thickening</li>
                                        <li>Paper making, petroleum and metallurgical process water</li>
