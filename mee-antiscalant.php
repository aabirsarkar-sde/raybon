                                    <h5>Evaporator equipment</h5>
                                    <p>Scale forms where heat transfer is highest, so knowing the equipment tells you where to expect it:</p>
                                    <ul>
                                        <li><strong>Pre-heater</strong> &mdash; raises feed to near boiling before the first effect; scales early where feed hardness is high</li>
                                        <li><strong>Calandria</strong> &mdash; the tube bundle where boiling occurs and the majority of scaling happens</li>
                                        <li><strong>VLS (vapour liquid separator)</strong> &mdash; separates vapour from concentrated liquor; foam carryover here contaminates condensate</li>
                                        <li><strong>ATFD</strong> &mdash; agitated thin film dryer taking concentrated brine to a dry solid at the end of the train</li>
                                    </ul>
                                    <p>For the complete train including RO, MVR and ATFD, see <a href="zld-chemicals.php">zero liquid discharge chemicals</a>.</p>

                                    <h5>Certified grades &mdash; NSF, Kiwa and food grade</h5>
                                    <p>Where the evaporator or its condensate feeds a potable or food-contact duty, the antiscalant and antifoam must carry the appropriate approval. We supply <strong>NSF certified</strong> and <strong>Kiwa certified</strong> grades, along with <strong>food grade antiscalant</strong> and <strong>drinking water grade</strong> products. Certification is granted per product and per maximum dose rate, so confirm both the certificate and the dose limit when specifying.</p>

                                    <h5>Antiscalant and antifoam together</h5>
                                    <p>Evaporators that scale usually foam as well. Concentrated organic liquor foams at the boiling surface, carrying COD into the condensate and causing bumping that destabilises the whole train. Sokalan AF is a pure organic, silicone-free antifoam that controls this at low dose without contaminating the condensate. Dosing antiscalant without addressing foam solves half the problem.</p>

