                                    <p><b>Multiple Effect Evaporators (MEE)</b> are used for evaporating high TDS and/ or high COD effluents in industrial applications, MEE Plants are installed wherever large volumes of water is required to be evaporated for concentration of salts, these plants are also used for concentrating RO rejects</p>

                                    <p>Scale formation in MEE Plants is a common phenomenon and it hinders the heat transfer process thereby reducing the overall efficiency of the system.</p>

                                    <p>Antiscalants are used to retard scale formation and antifoaming agents are used to retard foaming in MEE Plants , this ensures consistent performance of the MEE Plant and reduces cleaning frequency and condensate quality issues.</p>

