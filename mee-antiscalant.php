                                    <h5>The ranges we supply</h5>
                                    <p>We supply <strong>POC 3000</strong> and the <strong>Sokalan</strong> range for evaporator scale control, together with Sokalan AF antifoam for foam and COD carryover. Grades are selected against the liquor chemistry and concentration factor rather than from a catalogue.</p>

                                    <h5>Where MEE antiscalants are used</h5>
                                    <p>A multi effect evaporator concentrates effluent by boiling it across successive effects at falling pressure. As the liquor concentrates, sparingly soluble salts &mdash; calcium sulphate, calcium carbonate, silica and sodium salts &mdash; exceed solubility and deposit on the heat transfer surface. Antiscalant holds them in solution so the tubes stay clean, the heat transfer coefficient holds, and the plant runs longer between boil-outs.</p>
                                    <ul>
                                        <li><strong>Multi effect evaporator (MEE)</strong> trains in ZLD and effluent recycle plants</li>
                                        <li><strong>MVR</strong> (mechanical vapour recompression) evaporators</li>
                                        <li><strong>Thermal desalination</strong> &mdash; MED and MSF plants</li>
                                        <li>Falling film and forced circulation evaporators</li>
                                        <li>Crystallisers and brine concentrators downstream of RO reject</li>
                                    </ul>

