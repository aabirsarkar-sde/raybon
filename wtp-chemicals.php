                                    <p>A <strong>water treatment plant (WTP)</strong> prepares raw water for process, boiler feed or potable duty. Raybon Chemicals supplies clarification, filtration, softening and demineralisation chemistry along with the antiscalants and dosing equipment that keep those stages running.</p>

                                    <h5>Clarification and filtration</h5>
                                    <p>Raw and surface water is clarified with a coagulant followed by an <a href="anionic-polyelectrolytes.php">anionic polyelectrolyte</a> as a settling aid, then polished through sand and carbon filtration. Food-grade and potable-approved polymer grades are available for drinking water duty. See also <a href="portfolio-details-01.php">activated carbon</a>.</p>

                                    <h5>Softener</h5>
                                    <p>A <strong>softener</strong> exchanges calcium and magnesium for sodium across a resin bed, removing the hardness that would otherwise scale boilers, cooling systems and membranes. Softener performance is judged on hardness slip at the outlet and on regeneration efficiency &mdash; rising salt consumption for the same throughput usually indicates resin fouling rather than resin exhaustion.</p>

                                    <h5>DM plant</h5>
                                    <p>A <strong>DM plant</strong> (demineralisation plant) removes effectively all ionic content through cation and anion exchange, producing low-conductivity water for boiler feed and process duty. A degasser between the cation and anion stages strips carbon dioxide so the anion bed is not loaded with carbonic acid, which materially extends run length between regenerations.</p>

