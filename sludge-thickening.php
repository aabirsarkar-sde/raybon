                                    <h5>Thickening before dewatering</h5>
                                    <p>Plants that thicken properly usually spend less on polymer overall, not more. A decanter centrifuge fed at 4&ndash;5% solids runs at a fraction of the hydraulic load it carries at 1%, which lifts cake dryness, cuts run hours and reduces the polymer dose per tonne of dry solids.</p>

                                    <h5>Why thickening polymer differs from dewatering polymer</h5>
                                    <p>A thickening polymer must form a floc that drains or settles quickly under low shear. A dewatering polymer must form a floc that survives high shear and then gives up its water under pressure. The same grade rarely does both well, and using one polymer for both duties is a common source of poor thickener performance.</p>

