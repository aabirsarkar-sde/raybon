                                    <p>Polyelectrolyte only performs if it is prepared correctly. Dry powder polymer has to be wetted without forming fish-eyes, dissolved at the right concentration, and then aged long enough for the molecular chains to uncoil and develop their full molecular weight. A plant that dumps powder into a tank and doses it twenty minutes later is typically getting a fraction of the performance it has paid for &mdash; and compensating with a higher dose.</p>

                                    <p>Raybon Chemicals supplies <strong>polyelectrolyte solution preparation and automatic dosing systems</strong> sized to the plant, together with the polymer itself.</p>

                                    <h5>What a preparation and dosing system does</h5>
                                    <ul>
                                        <li><strong>Controlled wetting</strong> &mdash; powder is dispersed into water at a controlled rate so it hydrates evenly instead of forming undissolved lumps</li>
                                        <li><strong>Correct make-up concentration</strong> &mdash; typically 0.1&ndash;0.5% for powder polymer, above which the solution becomes too viscous to dose accurately</li>
                                        <li><strong>Ageing</strong> &mdash; a maturation stage giving the polymer time to develop full chain length before use</li>
                                        <li><strong>Automatic batching</strong> &mdash; a fresh batch is prepared as the working tank draws down, without operator intervention</li>
                                        <li><strong>Accurate dosing</strong> &mdash; metering pumps deliver a set dose against plant flow or a solids signal</li>
                                    </ul>

