                                    <h5>Textile effluent is a colour problem first</h5>
                                    <p>The defining characteristic of a dyeing house effluent is dissolved colour. It does not settle, it is not removed by a clarifier, and adding more polyelectrolyte will not touch it &mdash; polymer bridges suspended particles, and dissolved dye is not one. Removing colour needs precipitation chemistry that takes the dye out of solution first. This is the single most common misdiagnosis we see in this belt.</p>

                                    <h5>The rest of the load</h5>
                                    <ul>
                                        <li><strong>High hydraulic load</strong> &mdash; dyeing consumes large volumes, so plants are usually flow-limited rather than load-limited</li>
                                        <li><strong>Wide pH swing</strong> &mdash; batch processing sends alkaline and acidic slugs through in sequence</li>
                                        <li><strong>Surfactants and sizing agents</strong> &mdash; readily foaming, which reduces oxygen transfer in aeration</li>
                                        <li><strong>Variable temperature</strong> &mdash; hot effluent depresses biological activity and changes polymer behaviour</li>
                                        <li><strong>High sludge volumes</strong> &mdash; chemical sludge from colour precipitation adds to biological sludge</li>
                                    </ul>

