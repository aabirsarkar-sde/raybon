                                    <p>Where the treated stream feeds a reverse osmosis plant, a silicone-free defoamer is almost always the correct choice. Silicone carryover is one of the more common causes of irreversible membrane fouling, and it will not clean off.</p>

                                    <h5>Aerobic and anaerobic treatment</h5>
                                    <p>In <strong>aerobic treatment</strong>, foam in the aeration tank traps biomass at the surface, reduces oxygen transfer efficiency and spills solids over the launders. The defoamer has to break the foam without inhibiting the biomass doing the treatment &mdash; conventional defoamers often suppress the organisms along with the foam. In <strong>anaerobic treatment</strong>, foam in the digester carries over into gas lines and can blind the gas handling system entirely.</p>

