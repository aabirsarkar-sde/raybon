                                    <h5>Defoamer, antifoam and antifoaming agent</h5>
                                    <p>The terms are used interchangeably in the field, with a technical distinction: an <strong>antifoam</strong> is dosed before foam forms to prevent it, a <strong>defoamer</strong> is dosed onto existing foam to knock it down. Most products supplied for water and wastewater duty do both, and are sold as <strong>defoamer</strong>, <strong>antifoam</strong> or <strong>antifoaming agent</strong> according to the application.</p>

                                    <h5>Silicone and non-silicone defoamers</h5>
                                    <div class="rb-table-wrap">
                                    <table class="rb-spec">
                                        <thead><tr><th>Type</th><th>Strengths</th><th>Watch out for</th></tr></thead>
