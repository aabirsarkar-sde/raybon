                                    <h5>Blow down water</h5>
                                    <p><strong>Blow down</strong> is the deliberate bleed of concentrated circulating water, replaced by fresh make-up, that holds cycles at the design figure. Too little blowdown scales the system; too much wastes water, chemical and heat. Blowdown is usually controlled on conductivity.</p>

                                    <h5>Heat exchanger performance</h5>
                                    <p>Scale, corrosion product and biofilm on a <strong>heat exchanger</strong> surface all reduce heat transfer, and biofilm is by far the most efficient insulator of the three &mdash; a film too thin to see can cost more heat transfer than a visible scale layer. Approach temperature drifting upward at constant load is the usual first sign.</p>

                                    <h5>Monitoring and control</h5>
                                    <p>We supply the <strong>OnGuard</strong> cooling water control system from Solenis, which monitors corrosion, scale and biofilm continuously and controls chemical feed against actual system performance rather than a fixed dose. Control on measured performance is what allows cycles to be raised safely.</p>

