                                    <h5>Cycles of concentration (COC)</h5>
                                    <p>A cooling tower concentrates dissolved solids as water evaporates. <strong>Cycles of concentration (COC)</strong> is the ratio of dissolved solids in the circulating water to that in the <strong>make-up water</strong>, and it is the single most important number in a cooling water programme. Running higher cycles saves make-up water and blowdown volume, but pushes the circulating water closer to the scaling limit for calcium carbonate, sulphate and silica.</p>

