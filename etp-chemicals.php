                                    <h5>Chemical solution preparation and dosing</h5>
                                    <p>Chemistry only performs if it reaches the tank correctly prepared. A polyelectrolyte that has not been properly wetted and aged will not develop its molecular weight, and no amount of extra dose compensates. Chemical solution preparation tanks, dosing tanks and dosing pumps need to be sized to the make-up time of the product, not just to the flow. See our <a href="polyelectrolyte-dosing-system.php">polyelectrolyte solution preparation and auto dosing systems</a>.</p>

                                    <h5>Sludge handling</h5>
                                    <p>Primary, secondary and chemical sludge all need thickening and dewatering. Cationic polyelectrolyte is used for organic and biological sludge, anionic for inorganic and chemical sludge. See <a href="sludge-thickening.php">sludge thickening</a> and dewatering on the <a href="decanter-centrifuge.php">decanter centrifuge</a>, <a href="belt-press.php">belt press</a>, <a href="volute-screw-press.php">volute screw press</a> and <a href="filter-press.php">filter press</a>.</p>

