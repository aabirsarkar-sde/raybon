                                    <h5>Silica scaling</h5>
                                    <p>Silica is the hardest scale to reverse. Once polymerised on the membrane surface it will not respond to acid cleaning, and the flux loss is often permanent. Where reactive silica in the feed approaches its solubility limit at the operating pH and temperature, a silica-specific antiscalant is what allows recovery to be held without a permanent flux penalty. Sokalan RO 3000 and Sokalan RO 3500 are the grades we most often apply on high-silica bore-well feed.</p>

                                    <h5>Hardness, TDS and recovery</h5>
                                    <p>Feed hardness and TDS set the ceiling on how far the plant can be concentrated before a salt exceeds solubility in the reject. Raising recovery raises the concentration factor, so a plant pushed from 65% to 80% recovery may be operating well past the scaling threshold on hardness or sulphate. Antiscalant selection and dose follow from a projection of the reject chemistry &mdash; not from the feed analysis alone.</p>

                                    <h5>NSF certified antiscalants for potable water</h5>
                                    <p>RO plants producing drinking water require an antiscalant certified to <strong>NSF/ANSI 60</strong> for drinking water treatment chemicals. Certification is granted per product and per maximum dose rate, so confirm both the certificate and the dose limit when specifying an NSF antiscalant for a municipal or packaged drinking water plant. NSF certified grades are available within the ranges we supply.</p>

                                    <h5>RO fouling versus RO scaling</h5>
                                    <p>Scaling and fouling produce similar symptoms and need different chemistry. Scaling is crystalline salt deposition, usually worst in the last stage where concentration is highest. Fouling is deposition of colloids, biofilm, organics or iron, usually worst in the first stage where the feed enters. Dosing more antiscalant on a fouled plant achieves nothing. Normalised data &mdash; flow, differential pressure and salt rejection corrected for temperature and pressure &mdash; is what separates the two.</p>

