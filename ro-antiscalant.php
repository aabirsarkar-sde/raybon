                                    <h5>What an RO antiscalant does</h5>
                                    <p>A reverse osmosis antiscalant &mdash; also called a <strong>membrane antiscalant</strong> or scale inhibitor &mdash; is dosed into the RO feed to keep sparingly soluble salts in solution as the concentrate stream is progressively concentrated. It does not remove hardness. It holds scale-forming ions past their normal solubility limit long enough for them to leave the system in the reject, allowing the plant to run at higher recovery without scaling the membrane.</p>

