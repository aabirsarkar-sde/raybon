                                    <h5>Pre-treatment and dosing equipment</h5>
                                    <p>Most membrane scaling and fouling problems begin upstream of the membranes. The <strong>sand filter</strong> and <strong>carbon filter</strong> remove suspended solids, chlorine and organics; the <strong>cartridge filter</strong> is a final guard, not a treatment stage, and a cartridge filter changing rapidly is a symptom rather than a solution. The <strong>degasser</strong> strips carbon dioxide ahead of the anion stage in a DM train.</p>
                                    <ul>
                                        <li><strong>High pressure pump</strong> &mdash; delivers feed at operating pressure; rising pressure at constant flow indicates scaling or fouling</li>
                                        <li><strong>Acid dosing pump</strong> &mdash; trims feed pH to control carbonate scaling potential</li>
                                        <li><strong>Antiscalant dosing pump</strong> &mdash; must dose continuously and upstream of the cartridge filter so the antiscalant mixes fully before the membranes</li>
                                    </ul>
                                    <p>An antiscalant dosing pump that has drifted, air-locked or been left on a commissioning setting is one of the more common causes of unexplained scaling. Verify actual delivered dose against the projection before changing product.</p>

