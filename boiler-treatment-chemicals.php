                                    <h5>Deaerator</h5>
                                    <p>A <strong>deaerator</strong> strips dissolved oxygen and carbon dioxide from boiler feed water before it reaches the boiler. Dissolved oxygen is the primary driver of pitting corrosion in feed lines and tubes, and pitting perforates a tube long before general corrosion would. Mechanical deaeration is followed by an oxygen scavenger to remove the residual few parts per billion that the deaerator cannot.</p>

                                    <h5>Fire side and water side</h5>
                                    <p>A boiler has two distinct problem domains. The <strong>combustion chamber</strong> (burn chamber) and the fire side of the tubes deal with fuel, soot and flue gas; the water side deals with scale, corrosion and carryover. Water treatment chemistry acts on the water side only &mdash; it cannot fix a combustion or soot-fouling problem, and diagnosing one as the other wastes both time and chemical. Where efficiency has dropped, establishing which side the loss is on comes before any change to the treatment programme.</p>

                                    <h5>Boiler shell and tubes</h5>
                                    <p>Scale on the water side of <strong>boiler tubes</strong> insulates the heat transfer surface, raising tube metal temperature at constant firing. A thin scale layer can be enough to overheat a tube to failure. Internal treatment keeps hardness precipitated as a mobile sludge that blows down rather than as adherent scale on the <strong>boiler shell</strong> and tubes.</p>

                                    <h5>Condensate system</h5>
                                    <p><strong>Condensate</strong> return is the cheapest feed water a plant has &mdash; already hot and already demineralised. It is also the most corrosion-prone, because carbon dioxide carried over with steam forms carbonic acid on condensing and thins return lines from the inside. Neutralising or filming amines protect the condensate system; contaminated condensate should be dumped rather than returned.</p>

                                    <h5>Distribution systems and safety valves</h5>
                                    <p>Carryover of boiler water solids into the steam contaminates <strong>distribution systems</strong>, deposits on control valves and turbine blading, and can foul <strong>safety valves</strong> so that they fail to lift or fail to reseat. Foam control and correct blowdown are what keep carryover in check.</p>

